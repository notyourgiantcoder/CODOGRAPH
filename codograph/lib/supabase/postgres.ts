let pool: pg.Pool | null = null;

export function directPostgres(): pg.Pool | null {
  const url = process.env.DATABASE_URL?.trim();
  if (!url) return null;
  // One run writes on one connection; a second covers a run that overlaps it.
  pool ??= new pg.Pool({
    connectionString: url,
    ssl: { ca: SUPABASE_ROOT_CA, rejectUnauthorized: true },
    max: 2,
    idleTimeoutMillis: 10_000,
  });
  return pool;
}
